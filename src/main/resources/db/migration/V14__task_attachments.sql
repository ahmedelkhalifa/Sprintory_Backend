-- R25 (PMP-30, PMP-141, PMP-33): files attached to tasks. Contract: docs/attachments-docs.md.
-- The file itself lives on disk under app.attachments.dir, named by storage_key only; the user's
-- file name is display text and is never used as a path.
-- Deleting is soft: the row stays (the history names the file) but is never returned again.

create table task_attachments (
    id                   bigint generated by default as identity primary key,
    task_id              bigint                      not null,
    -- Null once the user account no longer exists; the attachment stays on the task.
    uploader_id          bigint,
    -- Display name only: last path segment, control characters removed, at most 255 characters.
    file_name            varchar(255)                not null,
    -- Detected from the content, never from the extension or the browser's Content-Type.
    file_type            varchar(10)                 not null,
    -- The stored size, after image compression, and the size as uploaded.
    size_bytes           bigint                      not null,
    original_size_bytes  bigint                      not null,
    -- Random UUID: the file's only name on disk.
    storage_key          varchar(36)                 not null,
    deleted_at           timestamp(6) with time zone,
    -- Who deleted it: the uploader or the Project Manager. No foreign key, like the audit log.
    deleted_by_id        bigint,
    created_at           timestamp(6),
    updated_at           timestamp(6),
    created_by           varchar(255),
    updated_by           varchar(255),
    constraint fk_task_attachments_task foreign key (task_id)
        references tasks (id) on delete cascade,
    constraint fk_task_attachments_uploader foreign key (uploader_id)
        references users (id) on delete set null,
    constraint uk_task_attachments_storage_key unique (storage_key),
    constraint ck_task_attachments_file_type check (file_type in (
        'PDF', 'DOCX', 'XLSX', 'PPTX', 'TXT', 'MD', 'CSV', 'PNG', 'JPEG', 'GIF', 'WEBP', 'ZIP')),
    constraint ck_task_attachments_sizes check (size_bytes > 0 and original_size_bytes > 0)
);
-- A task's list is always read for live attachments, newest first.
create index idx_task_attachments_task_time on task_attachments (task_id, created_at, id)
    where deleted_at is null;

-- Two new task history types (docs/task-history-docs.md §3.1).
alter table task_history drop constraint ck_task_history_type;
alter table task_history add constraint ck_task_history_type check (type in (
    'CREATED', 'FIELD_CHANGED', 'COMMENT_DELETED', 'SUBTASK_ADDED', 'SUBTASK_REMOVED', 'RESTORED',
    'ATTACHMENT_ADDED', 'ATTACHMENT_REMOVED'));