-- PMP-46 / PMP-150 (R12): milestones and linking tasks to them. Contract: docs/milestones-docs.md §8.
-- V20 is the Gantt's task dates (PMP-48). The check constraints below are extended from their
-- current definition rather than retyped, so values added by V20 or any earlier version are kept.

-- Soft-deleted (deleted_at); the name is unique per project among live milestones only, so a
-- deleted milestone's name can be used again. created_by_id is set to null when the account goes.
create table milestones (
    id             bigint generated by default as identity primary key,
    project_id     bigint                      not null,
    name           varchar(100)                not null,
    description    varchar(500),
    target_date    date                        not null,
    created_by_id  bigint,
    deleted_at     timestamp(6) with time zone,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    created_by     varchar(255),
    updated_by     varchar(255),
    constraint fk_milestones_project foreign key (project_id)
        references projects (id) on delete cascade,
    constraint fk_milestones_created_by foreign key (created_by_id)
        references users (id) on delete set null
);
create index idx_milestones_project on milestones (project_id);
create unique index uk_milestones_project_name on milestones (project_id, lower(name))
    where deleted_at is null;

-- One milestone per task; no link table. Deleting a milestone clears the column in the service;
-- the foreign key only covers the row going away with its project.
alter table tasks add column milestone_id bigint;
alter table tasks add constraint fk_tasks_milestone foreign key (milestone_id)
    references milestones (id) on delete set null;
create index idx_tasks_milestone on tasks (milestone_id);

-- Linking and unlinking a task is a FIELD_CHANGED entry with field MILESTONE.
do $$
declare old_expr text;
begin
    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid = 'task_history'::regclass and conname = 'ck_task_history_field';
    alter table task_history drop constraint ck_task_history_field;
    execute format('alter table task_history add constraint ck_task_history_field check ((%s) or field = ''MILESTONE'')', old_expr);
end $$;

-- Creating, editing, deleting and restoring a milestone is audited, with a MILESTONE target.
do $$
declare old_expr text;
begin
    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid = 'audit_log_entries'::regclass and conname = 'ck_audit_log_entries_action';
    alter table audit_log_entries drop constraint ck_audit_log_entries_action;
    execute format('alter table audit_log_entries add constraint ck_audit_log_entries_action check ((%s) or action in (''MILESTONE_CREATED'', ''MILESTONE_UPDATED'', ''MILESTONE_DELETED'', ''MILESTONE_RESTORED''))', old_expr);

    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid = 'audit_log_entries'::regclass and conname = 'ck_audit_log_entries_target_type';
    alter table audit_log_entries drop constraint ck_audit_log_entries_target_type;
    execute format('alter table audit_log_entries add constraint ck_audit_log_entries_target_type check ((%s) or target_type = ''MILESTONE'')', old_expr);
end $$;
