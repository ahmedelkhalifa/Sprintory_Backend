-- PMP-42 / PMP-156 (R17): the end-of-day totals of a sprint that the burndown reads.
-- Contract: docs/burndown-docs.md §5 and §8. One row per sprint and day, written as an upsert on
-- (sprint_id, snapshot_date) at start, nightly and at close/cancel.
create table sprint_daily_snapshots (
    id                bigint generated by default as identity primary key,
    sprint_id         bigint      not null references sprints (id) on delete cascade,
    snapshot_date     date        not null,
    total_points      integer     not null,
    remaining_points  integer     not null,
    total_tasks       integer     not null,
    remaining_tasks   integer     not null,
    unestimated_tasks integer     not null,
    recorded_at       timestamptz not null,
    constraint uq_sprint_daily_snapshots_sprint_date unique (sprint_id, snapshot_date)
);
