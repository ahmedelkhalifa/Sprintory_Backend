-- PMP-119: Sprint planning. Do not reuse a migration version: V14 is attachments.
-- Project row locks serialize sprint dates, status changes and task assignment mutations.
alter table projects add column sprint_length_days integer not null default 14
    constraint ck_projects_sprint_length check (sprint_length_days between 1 and 90);

create table sprints (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    sprint_number integer not null,
    name varchar(100) not null,
    goal text not null default '',
    capacity integer,
    start_date date,
    end_date date,
    status varchar(20) not null default 'PLANNED',
    completed_at timestamptz,
    committed_points integer,
    completed_points integer,
    created_at timestamp(6), updated_at timestamp(6), created_by varchar(255), updated_by varchar(255),
    constraint uq_sprint_number unique(project_id, sprint_number),
    constraint ck_sprint_status check (status in ('PLANNED', 'ACTIVE', 'COMPLETED')),
    constraint ck_sprint_dates check ((start_date is null and end_date is null) or
                                    (start_date is not null and end_date is not null and end_date > start_date)),
    constraint ck_sprint_capacity check (capacity is null or capacity >= 0)
);
create unique index uq_active_sprint_per_project on sprints(project_id) where status = 'ACTIVE';
create index idx_sprints_project_status on sprints(project_id, status);

alter table tasks add column sprint_id bigint references sprints(id) on delete set null;
alter table tasks add column sprint_position bigint;
create index idx_tasks_sprint_order on tasks(sprint_id, sprint_position) where deleted_at is null;

create table sprint_availability (
    id bigint generated by default as identity primary key,
    sprint_id bigint not null references sprints(id) on delete cascade,
    user_id bigint not null references users(id) on delete cascade,
    available_days integer not null check (available_days >= 0),
    constraint uq_sprint_availability unique(sprint_id, user_id)
);

create table sprint_commitments (
    id bigint generated by default as identity primary key,
    sprint_id bigint not null references sprints(id) on delete cascade,
    task_id bigint not null,
    task_key varchar(21) not null,
    committed_estimate integer,
    item_order integer not null,
    constraint uq_sprint_committed_task unique(sprint_id, task_id)
);

create table sprint_scope_changes (
    id bigint generated by default as identity primary key,
    sprint_id bigint not null references sprints(id) on delete cascade,
    task_id bigint not null,
    task_key varchar(21) not null,
    action varchar(16) not null check (action in ('ADDED', 'REMOVED')),
    actor_id bigint not null,
    changed_at timestamptz not null default now()
);
create index idx_sprint_scope_history on sprint_scope_changes(sprint_id, changed_at desc, id desc);
