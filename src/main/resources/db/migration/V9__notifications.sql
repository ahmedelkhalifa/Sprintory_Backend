-- R27 (PMP-32): in-app notifications, preferences, task watchers and the email outbox.
-- Contract: docs/notifications-docs.md.

create table notifications (
    id              bigint generated by default as identity primary key,
    recipient_id    bigint                      not null,
    type            varchar(40)                 not null,
    -- Null only for security notifications, which belong to a person, not a workspace.
    workspace_id    bigint,
    workspace_name  varchar(100),
    -- Snapshots, not references: a notification keeps showing a project, task or person that
    -- is gone, and opening it then answers 404. So project_id, task_id and actor_id have no
    -- foreign key. A null actor is the system (security notifications).
    project_id      bigint,
    project_key     varchar(10),
    project_name    varchar(100),
    task_id         bigint,
    task_key        varchar(21),
    task_title      varchar(255),
    actor_id        bigint,
    actor_name      varchar(512),
    message         varchar(1000)               not null,
    excerpt         varchar(300),
    created_at      timestamp(6) with time zone not null,
    read_at         timestamp(6) with time zone,
    constraint fk_notifications_recipient foreign key (recipient_id)
        references users (id) on delete cascade,
    -- A permanently deleted workspace takes its notifications with it.
    constraint fk_notifications_workspace foreign key (workspace_id)
        references workspaces (id) on delete cascade,
    constraint ck_notifications_type check (type in (
        'TASK_ASSIGNED', 'TASK_STATUS_CHANGED', 'TASK_COMMENTED', 'MENTIONED',
        'PROJECT_MEMBER_ADDED', 'PROJECT_ROLES_CHANGED',
        'SPRINT_STARTED', 'SPRINT_COMPLETED', 'SPRINT_CANCELLED',
        'WORKSPACE_INVITATION',
        'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED'))
);
-- The bell lists one person's notifications newest first; the partial index serves the unread
-- count and "mark all as read"; created_at serves the nightly 90-day cleanup.
create index idx_notifications_recipient_created
    on notifications (recipient_id, created_at desc, id desc);
create index idx_notifications_recipient_unread
    on notifications (recipient_id) where read_at is null;
create index idx_notifications_created_at on notifications (created_at);

-- Only the switches a person changed away from the default are stored, so a new user needs
-- no rows at all.
create table notification_preferences (
    user_id   bigint      not null,
    category  varchar(30) not null,
    channel   varchar(10) not null,
    enabled   boolean     not null,
    constraint pk_notification_preferences primary key (user_id, category, channel),
    constraint fk_notification_preferences_user foreign key (user_id)
        references users (id) on delete cascade,
    constraint ck_notification_preferences_category check (category in (
        'ASSIGNMENT', 'MENTION', 'COMMENT', 'STATUS_CHANGE', 'PROJECT_MEMBERSHIP', 'SPRINT',
        'INVITATION', 'SECURITY')),
    constraint ck_notification_preferences_channel check (channel in ('IN_APP', 'EMAIL'))
);

-- Tasks are soft-deleted, so watchers survive a delete and come back with a restore. The
-- cascade only fires when the task row itself goes (workspace delete).
create table task_watchers (
    task_id     bigint                      not null,
    user_id     bigint                      not null,
    created_at  timestamp(6) with time zone not null,
    constraint pk_task_watchers primary key (task_id, user_id),
    constraint fk_task_watchers_task foreign key (task_id)
        references tasks (id) on delete cascade,
    constraint fk_task_watchers_user foreign key (user_id)
        references users (id) on delete cascade
);
-- Leaving a project or workspace deletes the person's watcher rows there.
create index idx_task_watchers_user on task_watchers (user_id);

-- Notification emails are rendered and queued in the action's transaction, then sent and
-- retried by a background worker. No foreign keys: a queued email is self-contained.
create table email_outbox (
    id               bigint generated by default as identity primary key,
    recipient_email  varchar(255)                not null,
    subject          varchar(255)                not null,
    body_text        text                        not null,
    body_html        text                        not null,
    status           varchar(10)                 not null,
    attempts         integer                     not null,
    next_attempt_at  timestamp(6) with time zone,
    last_error       varchar(1000),
    created_at       timestamp(6) with time zone not null,
    sent_at          timestamp(6) with time zone,
    constraint ck_email_outbox_status check (status in ('PENDING', 'SENT', 'FAILED'))
);
-- The worker picks PENDING rows whose next attempt is due.
create index idx_email_outbox_due on email_outbox (status, next_attempt_at);