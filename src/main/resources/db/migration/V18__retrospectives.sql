-- PMP-44 / PMP-147 (R31): sprint retrospectives. Contract: docs/retrospectives-docs.md §8.
-- V17 is the Jira importer. Everything here cascades from the project, so deleting a project or
-- workspace removes its retros.

-- One retro per ended sprint. created_by_id / closed_by_id are set to null when the account goes,
-- so a retro outlives its author.
create table retrospectives (
    id             bigint generated by default as identity primary key,
    project_id     bigint                      not null,
    sprint_id      bigint                      not null,
    title          varchar(150)                not null,
    status         varchar(10)                 not null,
    created_by_id  bigint,
    closed_at      timestamp(6) with time zone,
    closed_by_id   bigint,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    created_by     varchar(255),
    updated_by     varchar(255),
    constraint uq_retrospectives_sprint unique (sprint_id),
    constraint fk_retrospectives_project foreign key (project_id)
        references projects (id) on delete cascade,
    constraint fk_retrospectives_sprint foreign key (sprint_id)
        references sprints (id) on delete cascade,
    constraint fk_retrospectives_created_by foreign key (created_by_id)
        references users (id) on delete set null,
    constraint fk_retrospectives_closed_by foreign key (closed_by_id)
        references users (id) on delete set null,
    constraint ck_retrospectives_status check (status in ('OPEN', 'CLOSED'))
);
create index idx_retrospectives_project on retrospectives (project_id);

-- Cards. The body is normalized TipTap JSON (docs/mentions-docs.md §2), like comments. Deleting
-- is soft and the card is never listed again; its votes are deleted at the same time.
create table retro_items (
    id           bigint generated by default as identity primary key,
    retro_id     bigint                      not null,
    column_name  varchar(20)                 not null,
    body         text                        not null,
    author_id    bigint,
    edited_at    timestamp(6) with time zone,
    deleted_at   timestamp(6) with time zone,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    created_by   varchar(255),
    updated_by   varchar(255),
    constraint fk_retro_items_retro foreign key (retro_id)
        references retrospectives (id) on delete cascade,
    constraint fk_retro_items_author foreign key (author_id)
        references users (id) on delete set null,
    constraint ck_retro_items_column check (column_name in ('WENT_WELL', 'TO_IMPROVE', 'IDEAS'))
);
-- A board is always read per retro, oldest first.
create index idx_retro_items_retro_time on retro_items (retro_id, created_at, id);

-- At most one vote per person per card; the 3-per-retro limit is checked under the retro row lock.
create table retro_votes (
    id        bigint generated by default as identity primary key,
    retro_id  bigint not null,
    item_id   bigint not null,
    user_id   bigint not null,
    constraint uq_retro_votes_item_user unique (item_id, user_id),
    constraint fk_retro_votes_retro foreign key (retro_id)
        references retrospectives (id) on delete cascade,
    constraint fk_retro_votes_item foreign key (item_id)
        references retro_items (id) on delete cascade,
    constraint fk_retro_votes_user foreign key (user_id)
        references users (id) on delete cascade
);
create index idx_retro_votes_retro_user on retro_votes (retro_id, user_id);

-- Action items are real tasks. The task holds the title, status and owner; the retro keeps the
-- link and a key snapshot, so a deleted task is still shown by key. Tasks are soft-deleted, so
-- the task cascade only fires when the task row itself goes (workspace delete).
create table retro_actions (
    id             bigint generated by default as identity primary key,
    retro_id       bigint                      not null,
    item_id        bigint,
    task_id        bigint                      not null,
    task_key       varchar(21)                 not null,
    created_by_id  bigint,
    created_at     timestamp(6) with time zone not null,
    constraint uq_retro_actions_task unique (task_id),
    constraint fk_retro_actions_retro foreign key (retro_id)
        references retrospectives (id) on delete cascade,
    constraint fk_retro_actions_item foreign key (item_id)
        references retro_items (id) on delete set null,
    constraint fk_retro_actions_task foreign key (task_id)
        references tasks (id) on delete cascade,
    constraint fk_retro_actions_created_by foreign key (created_by_id)
        references users (id) on delete set null
);
create index idx_retro_actions_retro on retro_actions (retro_id, created_at, id);

-- Notifications can point at a sprint, so the bell can open the sprint page (and its retro).
-- A snapshot with no foreign key, like project_id and task_id.
alter table notifications add column sprint_id bigint;
alter table notifications add column sprint_name varchar(100);

alter table notifications drop constraint ck_notifications_type;
alter table notifications add constraint ck_notifications_type check (type in (
    'TASK_ASSIGNED', 'TASK_STATUS_CHANGED', 'TASK_COMMENTED', 'MENTIONED',
    'PROJECT_MEMBER_ADDED', 'PROJECT_ROLES_CHANGED',
    'SPRINT_STARTED', 'SPRINT_COMPLETED', 'SPRINT_CANCELLED', 'SPRINT_OVERDUE',
    'RETRO_REMINDER', 'RETRO_OPENED', 'RETRO_CLOSED',
    'WORKSPACE_INVITATION',
    'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED'));

-- Closing a retro is audited; the target is its sprint.
alter table audit_log_entries drop constraint ck_audit_log_entries_action;
alter table audit_log_entries add constraint ck_audit_log_entries_action check (action in (
    'WORKSPACE_RENAMED', 'MEMBER_INVITED', 'MEMBER_JOINED', 'MEMBER_REMOVED', 'MEMBER_LEFT',
    'WORKSPACE_ROLE_CHANGED',
    'TEAM_CREATED', 'TEAM_RENAMED', 'TEAM_DELETED', 'TEAM_MEMBER_ADDED', 'TEAM_MEMBER_REMOVED',
    'PROJECT_CREATED', 'PROJECT_SETTINGS_CHANGED', 'PROJECT_MEMBER_ADDED', 'PROJECT_MEMBER_REMOVED',
    'PROJECT_ROLES_CHANGED',
    'SPRINT_COMPLETED', 'SPRINT_CANCELLED', 'RETRO_CLOSED',
    'TASK_DELETED', 'TASK_RESTORED',
    'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED'));
