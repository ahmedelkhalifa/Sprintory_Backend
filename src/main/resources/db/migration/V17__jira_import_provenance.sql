-- Sprintory Jira importer: provenance only. It never changes existing issue keys or Jira history.
create table jira_imported_issues (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    task_id bigint not null unique references tasks(id) on delete cascade,
    jira_issue_id varchar(60) not null,
    jira_key varchar(50) not null,
    jira_epic_key varchar(50),
    jira_created varchar(100),
    jira_updated varchar(100),
    constraint uq_jira_issue_id_per_project unique(project_id, jira_issue_id),
    constraint uq_jira_key_per_project unique(project_id, jira_key)
);
create index idx_jira_imported_issues_project on jira_imported_issues(project_id);

create table jira_imported_sprints (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    sprint_id bigint not null unique references sprints(id) on delete cascade,
    jira_sprint_id bigint not null,
    constraint uq_jira_sprint_per_project unique(project_id, jira_sprint_id)
);
