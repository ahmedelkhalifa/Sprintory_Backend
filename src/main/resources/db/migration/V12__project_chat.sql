-- PMP-137: one persisted, soft-deletable channel per project.
create table project_chat_messages (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects (id) on delete cascade,
    author_id bigint references users (id) on delete set null,
    author_name varchar(512) not null,
    content_json text,
    created_at timestamp(6) with time zone not null,
    edited_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    constraint ck_chat_deleted_content check (deleted_at is null or content_json is null)
);
create index idx_project_chat_history on project_chat_messages (project_id, id desc);
