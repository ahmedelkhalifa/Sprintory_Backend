-- PMP-116: project charter, ordered goals, external stakeholders, immutable goal/scope history.
-- Lifecycle column is a minimal foundation for PMP-63. Do not create another competing state field.
alter table projects add column lifecycle_status varchar(20) not null default 'ACTIVE';
alter table projects add constraint ck_projects_lifecycle_status
    check (lifecycle_status in ('ACTIVE', 'COMPLETED', 'ARCHIVED'));

create table project_charters (
    project_id bigint primary key references projects(id) on delete cascade,
    in_scope text,
    out_of_scope text,
    version bigint not null default 0
);
insert into project_charters(project_id) select id from projects;

create table charter_goals (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    title varchar(200) not null,
    success_measure varchar(1000),
    sort_order integer not null,
    constraint ck_charter_goals_title_not_blank check (length(btrim(title)) > 0),
    constraint ck_charter_goals_sort_order check (sort_order >= 0)
);
create index idx_charter_goals_project_order on charter_goals(project_id, sort_order, id);

create table charter_stakeholders (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    name varchar(200) not null,
    organization varchar(200),
    project_role varchar(100),
    interest varchar(10),
    influence varchar(10),
    contact_email varchar(254),
    linked_user_id bigint references users(id) on delete set null,
    constraint ck_charter_stakeholders_name_not_blank check (length(btrim(name)) > 0),
    constraint ck_charter_stakeholders_interest check (interest is null or interest in ('LOW','MEDIUM','HIGH')),
    constraint ck_charter_stakeholders_influence check (influence is null or influence in ('LOW','MEDIUM','HIGH'))
);
create index idx_charter_stakeholders_project on charter_stakeholders(project_id, id);

create table charter_history (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    actor_id bigint not null,
    actor_name varchar(400) not null,
    occurred_at timestamp(6) with time zone not null,
    change_type varchar(30) not null,
    old_value text,
    new_value text,
    constraint ck_charter_history_change_type check (change_type in (
        'GOAL_ADDED', 'GOAL_UPDATED', 'GOAL_DELETED', 'GOALS_REORDERED',
        'IN_SCOPE_CHANGED', 'OUT_OF_SCOPE_CHANGED'))
);
create index idx_charter_history_project_time on charter_history(project_id, occurred_at desc, id desc);
