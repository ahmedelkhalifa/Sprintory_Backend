-- R06: one persisted board per project, ordered workflow columns and optional WIP limits.
-- Existing projects are backfilled as well as new projects initialized by the service.
create table project_boards (
    project_id bigint primary key,
    constraint fk_project_boards_project foreign key (project_id)
        references projects (id) on delete cascade
);

create table project_board_columns (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    name varchar(100) not null,
    sort_order integer not null,
    wip_limit integer,
    constraint fk_project_board_columns_board foreign key (project_id)
        references project_boards (project_id) on delete cascade,
    constraint uk_project_board_columns_position unique (project_id, sort_order),
    constraint ck_project_board_columns_sort_order check (sort_order >= 0),
    constraint ck_project_board_columns_wip_limit check (wip_limit is null or wip_limit > 0)
);
create index idx_project_board_columns_project_id on project_board_columns (project_id);

insert into project_boards (project_id)
select id from projects;

insert into project_board_columns (project_id, name, sort_order)
select p.id, defaults.name, defaults.sort_order
from projects p
cross join (values (0, 'To Do'), (1, 'In Progress'), (2, 'Done'))
    as defaults(sort_order, name)
where p.template = 'SCRUM';

insert into project_board_columns (project_id, name, sort_order)
select p.id, defaults.name, defaults.sort_order
from projects p
cross join (values (0, 'To Do'), (1, 'In Progress'), (2, 'In Review'), (3, 'Done'))
    as defaults(sort_order, name)
where p.template = 'KANBAN';
