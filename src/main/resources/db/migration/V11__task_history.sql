-- R10 (PMP-133): task history and task comments, in one migration.
--  1. One activity feed per task, replacing the status-only task_status_history of V7.
--     Contract: docs/task-history-docs.md. Append-only: the application never updates or
--     deletes a row.
--  2. Comments on tasks (end of the file). Contract: docs/comments-docs.md.

create table task_history (
    id           bigint generated by default as identity primary key,
    task_id      bigint                      not null,
    type         varchar(30)                 not null,
    -- Only for FIELD_CHANGED: which field changed.
    field        varchar(30),
    -- Display snapshots (names, not ids), so a later rename does not change the past.
    old_value    text,
    new_value    text,
    -- The comment or subtask the entry is about, for COMMENT_DELETED and SUBTASK_*.
    ref_id       bigint,
    -- No foreign key on purpose: an entry outlives its author, as in the audit log.
    actor_id     bigint                      not null,
    actor_name   varchar(512)                not null,
    occurred_at  timestamp(6) with time zone not null,
    constraint fk_task_history_task foreign key (task_id)
        references tasks (id) on delete cascade,
    constraint ck_task_history_type check (type in (
        'CREATED', 'FIELD_CHANGED', 'COMMENT_DELETED', 'SUBTASK_ADDED', 'SUBTASK_REMOVED', 'RESTORED')),
    constraint ck_task_history_field check (field in (
        'TITLE', 'TYPE', 'PRIORITY', 'STATUS', 'ASSIGNEE', 'ESTIMATE', 'ESTIMATE_MINUTES',
        'LABELS', 'DESCRIPTION')),
    constraint ck_task_history_field_only_for_changes check ((type = 'FIELD_CHANGED') = (field is not null))
);
-- The feed is always read per task, oldest first.
create index idx_task_history_task_time on task_history (task_id, occurred_at, id);

-- Keep every status move recorded so far (PMP-125). Column ids are not kept, only the names.
insert into task_history (task_id, type, field, old_value, new_value, actor_id, actor_name, occurred_at)
select h.task_id, 'FIELD_CHANGED', 'STATUS', h.from_column_name, h.to_column_name, h.actor_id,
       coalesce(nullif(trim(u.first_name || ' ' || u.last_name), ''), 'Deleted user'), h.changed_at
from task_status_history h
left join users u on u.id = h.actor_id
order by h.changed_at, h.id;

drop table task_status_history;

-- 2. Task comments. The body is normalized TipTap JSON (docs/mentions-docs.md §2).
-- Deleting is soft: the row stays as a "Comment deleted" placeholder; its text is never returned.
create table task_comments (
    id             bigint generated by default as identity primary key,
    task_id        bigint                      not null,
    -- Null once the user account no longer exists; the thread stays readable.
    author_id      bigint,
    body           text                        not null,
    -- Set when the text really changed; the frontend shows "(edited)".
    edited_at      timestamp(6) with time zone,
    deleted_at     timestamp(6) with time zone,
    -- Who deleted it: the author or the Project Manager. No foreign key, like the audit log.
    deleted_by_id  bigint,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    created_by     varchar(255),
    updated_by     varchar(255),
    constraint fk_task_comments_task foreign key (task_id)
        references tasks (id) on delete cascade,
    constraint fk_task_comments_author foreign key (author_id)
        references users (id) on delete set null
);
-- A thread is always read per task, oldest first.
create index idx_task_comments_task_time on task_comments (task_id, created_at, id);