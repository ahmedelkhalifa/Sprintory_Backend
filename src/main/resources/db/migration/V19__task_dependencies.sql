-- PMP-45: retained directed links. V18 is reserved for retrospectives; coordinate V19 before merge.
-- Composite foreign keys make cross-project edges impossible even outside the service.
alter table tasks add constraint uk_tasks_project_id unique (project_id, id);
create table task_dependency (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    blocker_task_id bigint not null,
    blocked_task_id bigint not null,
    created_by bigint references users(id) on delete set null,
    created_at timestamp(6) with time zone not null,
    constraint fk_dependency_blocker foreign key (project_id, blocker_task_id)
        references tasks(project_id, id) on delete cascade,
    constraint fk_dependency_blocked foreign key (project_id, blocked_task_id)
        references tasks(project_id, id) on delete cascade,
    constraint uk_dependency_pair unique (blocker_task_id, blocked_task_id),
    constraint ck_dependency_not_self check (blocker_task_id <> blocked_task_id)
);
create index idx_dependency_project on task_dependency(project_id);
create index idx_dependency_blocked on task_dependency(blocked_task_id);
