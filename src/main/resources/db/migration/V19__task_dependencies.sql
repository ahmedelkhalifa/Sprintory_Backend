-- PMP-45: retained directed links.
-- Composite foreign keys make cross-project edges impossible even outside the service.
alter table tasks add constraint uk_tasks_project_id unique (project_id, id);
create table task_dependency (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    blocker_task_id bigint not null,
    blocked_task_id bigint not null,
    created_by bigint references users(id) on delete set null,
    created_at timestamp(6) with time zone not null,
    constraint fk_dependency_blocker foreign key (project_id, blocker_task_id)
        references tasks(project_id, id) on delete cascade,
    constraint fk_dependency_blocked foreign key (project_id, blocked_task_id)
        references tasks(project_id, id) on delete cascade,
    constraint uk_dependency_pair unique (blocker_task_id, blocked_task_id),
    constraint ck_dependency_not_self check (blocker_task_id <> blocked_task_id)
);
create index idx_dependency_project on task_dependency(project_id);
create index idx_dependency_blocked on task_dependency(blocked_task_id);

-- Add new history values without discarding any earlier sprint's allowed values.
do $$
declare old_expr text;
begin
    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid='task_history'::regclass and conname='ck_task_history_type';
    alter table task_history drop constraint ck_task_history_type;
    execute format('alter table task_history add constraint ck_task_history_type check ((%s) or type in (''DEPENDENCY_ADDED'',''DEPENDENCY_REMOVED''))', old_expr);
end $$;

-- Preserve earlier notification values, including any retrospective types introduced by V18.
do $$
declare old_expr text;
begin
    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid='notifications'::regclass and conname='ck_notifications_type';
    alter table notifications drop constraint ck_notifications_type;
    execute format('alter table notifications add constraint ck_notifications_type check ((%s) or type = ''TASK_UNBLOCKED'')', old_expr);
end $$;
