-- R05 (PMP-24): append-only workspace audit log. Contract: docs/audit-log-docs.md.

create table audit_log_entries (
    id            bigint generated by default as identity primary key,
    workspace_id  bigint                      not null,
    occurred_at   timestamp(6) with time zone not null,
    action        varchar(50)                 not null,
    -- Snapshots, not references: an entry must keep showing a person who left the workspace
    -- or a project that no longer exists, so actor_id and project_id have no foreign key.
    -- A null actor is the system (LOGIN_FAILED_REPEATED).
    actor_id      bigint,
    actor_name    varchar(512),
    actor_email   varchar(255),
    target_type   varchar(20)                 not null,
    target_id     bigint,
    target_name   varchar(512)                not null,
    project_id    bigint,
    project_name  varchar(100),
    -- A permanently deleted workspace takes its log with it: nobody could read it any more.
    constraint fk_audit_log_entries_workspace foreign key (workspace_id)
        references workspaces (id) on delete cascade,
    constraint ck_audit_log_entries_action check (action in (
        'WORKSPACE_RENAMED', 'MEMBER_INVITED', 'MEMBER_JOINED', 'MEMBER_REMOVED', 'MEMBER_LEFT',
        'WORKSPACE_ROLE_CHANGED',
        'TEAM_CREATED', 'TEAM_RENAMED', 'TEAM_DELETED', 'TEAM_MEMBER_ADDED', 'TEAM_MEMBER_REMOVED',
        'PROJECT_CREATED', 'PROJECT_SETTINGS_CHANGED', 'PROJECT_MEMBER_ADDED', 'PROJECT_MEMBER_REMOVED',
        'PROJECT_ROLES_CHANGED',
        'TASK_DELETED', 'TASK_RESTORED',
        'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED')),
    constraint ck_audit_log_entries_target_type check (target_type in (
        'WORKSPACE', 'TEAM', 'PROJECT', 'TASK', 'USER', 'INVITATION'))
);
-- The log is always read per workspace, newest first; the other two serve the actor and
-- project filters and the actor list.
create index idx_audit_log_entries_workspace_time
    on audit_log_entries (workspace_id, occurred_at desc, id desc);
create index idx_audit_log_entries_workspace_actor on audit_log_entries (workspace_id, actor_id);
create index idx_audit_log_entries_workspace_project on audit_log_entries (workspace_id, project_id);

-- The old -> new values of one entry, in a fixed order per action.
create table audit_log_changes (
    entry_id   bigint      not null,
    sort_order integer     not null,
    field      varchar(50) not null,
    old_value  text,
    new_value  text,
    constraint pk_audit_log_changes primary key (entry_id, sort_order),
    constraint fk_audit_log_changes_entry foreign key (entry_id)
        references audit_log_entries (id) on delete cascade
);