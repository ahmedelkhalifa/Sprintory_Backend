-- R19 / PMP-49 / PMP-144. Apply after V22.
create table time_entry (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null references workspaces(id) on delete cascade,
    project_id bigint not null references projects(id) on delete cascade,
    task_id bigint not null references tasks(id) on delete cascade,
    -- Retain attribution even if membership or the user account disappears.
    user_id bigint not null,
    work_date date not null,
    minutes integer not null,
    note varchar(500),
    created_at timestamp(6),
    updated_at timestamp(6),
    created_by varchar(255),
    updated_by varchar(255),
    deleted_at timestamp(6) with time zone,
    constraint ck_time_entry_minutes check (minutes between 1 and 1440)
);
create index idx_time_entry_user_date on time_entry(user_id, work_date, workspace_id) where deleted_at is null;
create index idx_time_entry_task on time_entry(task_id) where deleted_at is null;
create index idx_time_entry_project on time_entry(project_id);
create index idx_time_entry_workspace on time_entry(workspace_id);

-- Preserve any history types introduced by other features (including V22).
do $$
declare old_expr text;
begin
    select pg_get_expr(conbin, conrelid) into strict old_expr from pg_constraint
        where conrelid = 'task_history'::regclass and conname = 'ck_task_history_type';
    alter table task_history drop constraint ck_task_history_type;
    execute format('alter table task_history add constraint ck_task_history_type check ((%s) or type in (''TIME_ENTRY_ADDED'', ''TIME_ENTRY_CHANGED'', ''TIME_ENTRY_DELETED''))', old_expr);
end $$;
