-- PMP-40 / PMP-41 (R15): close or cancel a sprint and carry over unfinished work.
-- V15 is merged and frozen; every sprint schema change from here on is a new version.

-- A sprint ends as COMPLETED (closed by the Scrum Master) or CANCELLED (Product Owner or
-- Project Manager). completed_at is the moment it ended, for both.
alter table sprints drop constraint ck_sprint_status;
alter table sprints add constraint ck_sprint_status
    check (status in ('PLANNED', 'ACTIVE', 'COMPLETED', 'CANCELLED'));

-- Frozen at the end: later estimate edits never change them.
alter table sprints add column unfinished_points integer;
alter table sprints add column goal_achieved varchar(20)
    constraint ck_sprint_goal_achieved check (goal_achieved in ('YES', 'PARTIALLY', 'NO'));
alter table sprints add column outcome_note text;
alter table sprints add column cancel_reason text;

-- "Carried over xN": how many times an unfinished task left an ended sprint.
alter table tasks add column carry_over_count integer not null default 0
    constraint ck_tasks_carry_over_count check (carry_over_count >= 0);

-- One frozen row per top-level item of an ended sprint, for velocity and reports (R17, R22).
-- task_id has no foreign key on purpose, like sprint_commitments: the result outlives the task.
create table sprint_outcomes (
    id bigint generated by default as identity primary key,
    sprint_id bigint not null references sprints(id) on delete cascade,
    task_id bigint not null,
    task_key varchar(21) not null,
    estimate integer,
    outcome varchar(20) not null,
    destination_sprint_id bigint,
    item_order integer not null,
    constraint uq_sprint_outcome_task unique (sprint_id, task_id),
    constraint ck_sprint_outcome check (outcome in ('DONE', 'CARRIED_OVER'))
);

-- A carried-over task records its source sprint in its own history.
alter table task_history drop constraint ck_task_history_type;
alter table task_history add constraint ck_task_history_type check (type in (
    'CREATED', 'FIELD_CHANGED', 'COMMENT_DELETED', 'SUBTASK_ADDED', 'SUBTASK_REMOVED',
    'RESTORED', 'ATTACHMENT_ADDED', 'ATTACHMENT_REMOVED', 'SPRINT_SCOPE_CHANGED', 'CARRIED_OVER'));

-- Closing and cancelling are audited; the target is the sprint.
alter table audit_log_entries drop constraint ck_audit_log_entries_action;
alter table audit_log_entries add constraint ck_audit_log_entries_action check (action in (
    'WORKSPACE_RENAMED', 'MEMBER_INVITED', 'MEMBER_JOINED', 'MEMBER_REMOVED', 'MEMBER_LEFT',
    'WORKSPACE_ROLE_CHANGED',
    'TEAM_CREATED', 'TEAM_RENAMED', 'TEAM_DELETED', 'TEAM_MEMBER_ADDED', 'TEAM_MEMBER_REMOVED',
    'PROJECT_CREATED', 'PROJECT_SETTINGS_CHANGED', 'PROJECT_MEMBER_ADDED', 'PROJECT_MEMBER_REMOVED',
    'PROJECT_ROLES_CHANGED',
    'SPRINT_COMPLETED', 'SPRINT_CANCELLED',
    'TASK_DELETED', 'TASK_RESTORED',
    'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED'));
alter table audit_log_entries drop constraint ck_audit_log_entries_target_type;
alter table audit_log_entries add constraint ck_audit_log_entries_target_type check (target_type in (
    'WORKSPACE', 'TEAM', 'PROJECT', 'SPRINT', 'TASK', 'USER', 'INVITATION'));

-- Daily reminder to the Scrum Masters while an active sprint is past its end date.
alter table notifications drop constraint ck_notifications_type;
alter table notifications add constraint ck_notifications_type check (type in (
    'TASK_ASSIGNED', 'TASK_STATUS_CHANGED', 'TASK_COMMENTED', 'MENTIONED',
    'PROJECT_MEMBER_ADDED', 'PROJECT_ROLES_CHANGED',
    'SPRINT_STARTED', 'SPRINT_COMPLETED', 'SPRINT_CANCELLED', 'SPRINT_OVERDUE',
    'WORKSPACE_INVITATION',
    'PASSWORD_RESET', 'LOGIN_FAILED_REPEATED'));