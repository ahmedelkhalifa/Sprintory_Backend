-- R02: workspaces, invitations, teams and projects.
-- Never edit this file once merged; add V3__... for every later change.

-- Users have no role any more (decided 23 Oct 2026); roles live on workspace_members.
-- Dropping the column also drops ck_users_role.
alter table users drop column role;

create table workspaces (
    id           bigint generated by default as identity primary key,
    name         varchar(100)                not null,
    slug         varchar(100)                not null,
    archived_at  timestamp(6) with time zone,          -- null while active
    created_at   timestamp(6),
    updated_at   timestamp(6),
    created_by   varchar(255),
    updated_by   varchar(255),
    constraint uk_workspaces_slug unique (slug)
);

create table workspace_members (
    id            bigint generated by default as identity primary key,
    workspace_id  bigint       not null,
    user_id       bigint       not null,
    role          varchar(255) not null,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    created_by    varchar(255),
    updated_by    varchar(255),
    constraint uk_workspace_members_workspace_user unique (workspace_id, user_id),
    constraint fk_workspace_members_workspace foreign key (workspace_id) references workspaces (id) on delete cascade,
    constraint fk_workspace_members_user foreign key (user_id) references users (id) on delete cascade,
    constraint ck_workspace_members_role check (role in ('WORKSPACE_MEMBER', 'WORKSPACE_ADMIN'))
);
-- The unique constraint covers lookups by workspace; "my workspaces" looks up by user
create index idx_workspace_members_user_id on workspace_members (user_id);

create table workspace_invitations (
    id            bigint generated by default as identity primary key,
    workspace_id  bigint                      not null,
    email         varchar(255)                not null,
    token_hash    varchar(64)                 not null,
    expires_at    timestamp(6) with time zone not null,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    created_by    varchar(255),
    updated_by    varchar(255),
    constraint uk_workspace_invitations_workspace_email unique (workspace_id, email),
    constraint uk_workspace_invitations_token_hash unique (token_hash),
    constraint fk_workspace_invitations_workspace foreign key (workspace_id) references workspaces (id) on delete cascade
);

create table teams (
    id            bigint generated by default as identity primary key,
    workspace_id  bigint       not null,
    name          varchar(100) not null,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    created_by    varchar(255),
    updated_by    varchar(255),
    constraint uk_teams_workspace_name unique (workspace_id, name),
    constraint fk_teams_workspace foreign key (workspace_id) references workspaces (id) on delete cascade
);

create table team_members (
    id          bigint generated by default as identity primary key,
    team_id     bigint not null,
    user_id     bigint not null,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    created_by  varchar(255),
    updated_by  varchar(255),
    constraint uk_team_members_team_user unique (team_id, user_id),
    constraint fk_team_members_team foreign key (team_id) references teams (id) on delete cascade,
    constraint fk_team_members_user foreign key (user_id) references users (id) on delete cascade
);
create index idx_team_members_user_id on team_members (user_id);

create table projects (
    id            bigint generated by default as identity primary key,
    workspace_id  bigint       not null,
    name          varchar(100) not null,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    created_by    varchar(255),
    updated_by    varchar(255),
    constraint fk_projects_workspace foreign key (workspace_id) references workspaces (id) on delete cascade
);
-- Postgres does not index foreign keys itself; projects are listed per workspace
create index idx_projects_workspace_id on projects (workspace_id);

create table project_members (
    id          bigint generated by default as identity primary key,
    project_id  bigint not null,
    user_id     bigint not null,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    created_by  varchar(255),
    updated_by  varchar(255),
    constraint uk_project_members_project_user unique (project_id, user_id),
    constraint fk_project_members_project foreign key (project_id) references projects (id) on delete cascade,
    constraint fk_project_members_user foreign key (user_id) references users (id) on delete cascade
);
create index idx_project_members_user_id on project_members (user_id);