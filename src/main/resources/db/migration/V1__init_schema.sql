-- Baseline schema: what the User, RefreshToken and OneTimeToken entities map to.
-- Never edit this file once merged; add V2__..., V3__... for every later change.

create table users (
    id          bigint generated by default as identity primary key,
    first_name  varchar(255) not null,
    last_name   varchar(255) not null,
    email       varchar(255) not null,
    password    varchar(255),                 -- null for Google accounts
    enabled     boolean      not null,
    provider    varchar(255) not null,
    role        varchar(255) not null,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    created_by  varchar(255),
    updated_by  varchar(255),
    constraint uk_users_email    unique (email),
    constraint ck_users_provider check (provider in ('LOCAL', 'GOOGLE')),
    constraint ck_users_role     check (role in ('WORKSPACE_MEMBER', 'WORKSPACE_ADMIN'))
);

create table refresh_tokens (
    id           bigint generated by default as identity primary key,
    token_hash   varchar(64)                 not null,
    user_id      bigint                      not null,
    expires_at   timestamp(6) with time zone not null,
    remember_me  boolean                     not null default true,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    created_by   varchar(255),
    updated_by   varchar(255),
    constraint uk_refresh_tokens_token_hash unique (token_hash),
    constraint fk_refresh_tokens_user foreign key (user_id) references users (id) on delete cascade
);
-- Postgres does not index foreign keys itself; logout-all looks tokens up by user
create index idx_refresh_tokens_user_id on refresh_tokens (user_id);

create table one_time_tokens (
    id           bigint generated by default as identity primary key,
    token_hash   varchar(64)                 not null,
    user_id      bigint                      not null,
    purpose      varchar(255)                not null,
    expires_at   timestamp(6) with time zone not null,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    created_by   varchar(255),
    updated_by   varchar(255),
    constraint uk_one_time_tokens_token_hash unique (token_hash),
    constraint fk_one_time_tokens_user foreign key (user_id) references users (id) on delete cascade,
    constraint ck_one_time_tokens_purpose check (purpose in ('VERIFY_EMAIL', 'RESET_PASSWORD'))
);
-- Issuing a new link deletes the user's older links of the same purpose
create index idx_one_time_tokens_user_purpose on one_time_tokens (user_id, purpose);