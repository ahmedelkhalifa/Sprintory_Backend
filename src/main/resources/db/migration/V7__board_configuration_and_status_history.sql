ALTER TABLE project_board_columns DROP CONSTRAINT IF EXISTS uk_project_board_columns_position;
CREATE UNIQUE INDEX uq_board_column_live_position
    ON project_board_columns (project_id, sort_order) WHERE deleted_at IS NULL;
