UPDATE project_board_columns
SET category = CASE
    WHEN lower(name) = 'done' THEN 'DONE'
    WHEN lower(name) IN ('in progress', 'in review') THEN 'IN_PROGRESS'
    ELSE 'TODO'
END;
ALTER TABLE project_board_columns ALTER COLUMN category SET NOT NULL;
ALTER TABLE project_board_columns
    ADD CONSTRAINT ck_board_column_category CHECK (category IN ('TODO', 'IN_PROGRESS', 'DONE'));

