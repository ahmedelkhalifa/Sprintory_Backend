CREATE TABLE task_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    from_column_id bigint NOT NULL,
    to_column_id bigint NOT NULL,
    from_column_name varchar(100) NOT NULL,
    to_column_name varchar(100) NOT NULL,
    actor_id bigint NOT NULL,
    changed_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_task_status_history_task ON task_status_history (task_id, changed_at, id);
