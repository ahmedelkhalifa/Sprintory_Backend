-- R09 (story 9): tasks with per-project keys, labels and soft delete.

-- Per-project counter behind the task keys (MOB-1, MOB-2, ...). Only ever incremented, so a
-- deleted task's key is never handed out again.
alter table projects add column last_task_number integer not null default 0;

create table tasks (
    id                bigint generated by default as identity primary key,
    project_id        bigint       not null,
    task_number       integer      not null,
    task_key          varchar(21)  not null,
    title             varchar(255) not null,
    type              varchar(255) not null,
    priority          varchar(255) not null,
    status_column_id  bigint       not null,
    assignee_id       bigint,
    estimate          integer,
    description       text,
    -- Order inside the status column and in the product backlog. Sparse (1,000,000 apart) so a
    -- move takes the midpoint between its neighbours and updates one row; see TaskRanks.
    board_position    bigint       not null,
    backlog_rank      bigint       not null,
    deleted_at        timestamp(6) with time zone,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    created_by        varchar(255),
    updated_by        varchar(255),
    constraint uk_tasks_project_number unique (project_id, task_number),
    constraint fk_tasks_project foreign key (project_id) references projects (id) on delete cascade,
    -- No cascade: removing a board column must never delete tasks silently. NO ACTION is
    -- checked at the end of the statement, so deleting a project or workspace (which cascades
    -- to its columns and its tasks) still works.
    constraint fk_tasks_status_column foreign key (status_column_id)
        references project_board_columns (id),
    constraint fk_tasks_assignee foreign key (assignee_id) references users (id) on delete set null,
    constraint ck_tasks_type check (type in ('STORY', 'TASK', 'BUG')),
    constraint ck_tasks_priority check (priority in ('HIGHEST', 'HIGH', 'MEDIUM', 'LOW', 'LOWEST')),
    constraint ck_tasks_estimate check (estimate is null or estimate >= 0)
);
-- Task lists are always per project and leave deleted tasks out.
create index idx_tasks_project_id_deleted_at on tasks (project_id, deleted_at);
create index idx_tasks_status_column_id on tasks (status_column_id);
create index idx_tasks_assignee_id on tasks (assignee_id);
-- The board reads a column in order; the backlog reads the project in order.
create index idx_tasks_board_order on tasks (project_id, status_column_id, board_position);
create index idx_tasks_backlog_order on tasks (project_id, backlog_rank);

create table task_labels (
    task_id  bigint      not null,
    label    varchar(50) not null,
    constraint pk_task_labels primary key (task_id, label),
    constraint fk_task_labels_task foreign key (task_id) references tasks (id) on delete cascade
);